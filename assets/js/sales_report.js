"use strict";

document.addEventListener("DOMContentLoaded", () => {

    /* ======================================
       CSV EXPORT
       Data is generated by sales_report.php
    ====================================== */

    const exportButton = document.getElementById("exportCsv");

    if (exportButton) {
        exportButton.addEventListener("click", () => {

            // Keep the existing href="?export=csv".
            // The PHP backend generates the CSV.

            exportButton.classList.add("is-exporting");

            exportButton.setAttribute(
                "aria-label",
                "Downloading sales report CSV"
            );

        });
    }

    /* ======================================
       CATEGORY REVENUE BARS
       Widths come from PHP calculations
    ====================================== */

    const bars = document.querySelectorAll(
        ".category-bar-fill"
    );

    bars.forEach((bar) => {

        const width = bar.style.width;

        // Ensure category bars cannot exceed 100%.
        const value = Number.parseFloat(width);

        if (!Number.isFinite(value)) {
            bar.style.width = "0%";
            return;
        }

        const percentage = Math.min(
            100,
            Math.max(0, value)
        );

        bar.style.width = `${percentage}%`;

    });

});
